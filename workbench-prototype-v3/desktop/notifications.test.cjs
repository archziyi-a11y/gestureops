const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createNotifier, observations } = require('./notifications.cjs');
test('persistent episodes, recovery, escalation, pause, and failed reads', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wb-toast-'));
  const file = path.join(dir, 'state.json');
  const deliveries = [];
  const make = () => createNotifier({ file, deliver: rows => deliveries.push(rows) });
  let monitor = make();
  const row = { id: 'a', active: true, severity: 'normal', episode: 'one' };
  await monitor.accept([row]);
  await monitor.accept([{ ...row, title: 'changed timestamp/count' }]);
  monitor = make();
  await monitor.accept([row]);
  await monitor.accept(observations(null, null));
  await monitor.accept([row]);
  assert.equal(deliveries.length, 1);
  await monitor.accept([{ ...row, severity: 'severe' }]);
  assert.equal(deliveries.length, 2);
  await monitor.accept([{ id: 'a', active: false }]);
  await monitor.accept([row]);
  assert.equal(deliveries.length, 3);
  monitor.setEnabled(false);
  await monitor.accept([{ id: 'b', active: true }]);
  assert.equal(deliveries.length, 3);
  monitor.setEnabled(true);
  await monitor.accept([{ id: 'b', active: true }]);
  assert.equal(deliveries.length, 4);
  await monitor.accept([{ ...row, episode: 'two' }]);
  assert.equal(deliveries.length, 5);
  monitor.setEnabled(false);
  await monitor.accept([{ ...row, episode: 'three' }]);
  monitor.setEnabled(true);
  await monitor.accept([{ ...row, episode: 'three' }]);
  assert.equal(deliveries.length, 6);
});
test('card and incident sources, missing cards do not imply resolution', () => {
  assert.deepEqual(observations(null, { cards: [] }), []);
  const rows = observations({ issues: [{ id: 'incident:balance:1', project: 'bridge' }], history: [] }, { cards: [{ id: 'bridge', issue: 'balance' }, { id: 'reports', issue: 'quota' }, { id: 'jyq' }] });
  assert.equal(rows.length, 3);
  assert.equal(rows[1].active, true);
  assert.equal(rows[2].active, false);
});
