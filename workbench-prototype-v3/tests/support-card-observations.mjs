import assert from 'node:assert/strict';
import {readSupportCards} from '../src/domain/support-card-observations.js';
const result=await readSupportCards({root:'.',balance:{connections:{sales:{balances:[{currency:'CNY',total:'3.2'}],checkedAt:'2026-11-10T02:00:00Z',key:'secret'},knowledge:{error:'secret'}}},inspect:async()=>({isFile:()=>true})});
assert.match(result.cards[0].fact,/¥3.20（余额偏低）/);
assert.match(result.cards[0].fact,/知识试问 尚无余额记录（更新失败）/);
assert.match(result.cards[1].fact,/可准备销售助手部署与迁移/);
assert.ok(!JSON.stringify(result).includes('secret'));
assert.equal(result.cards[0].balances.length,3);
assert.equal(result.cards[0].balances[2].id,'dock');
assert.equal(result.cards[0].balances[1].amount,null);
assert.match(result.cards[0].detail,/知识试问：尚未成功查询；本次查询失败/);
assert.doesNotMatch(result.cards[0].detail,/保留上次余额/);
assert.equal(result.cards[1].documents.length,3);
const stale=await readSupportCards({root:'.',balance:{connections:{dock:{balances:[{currency:'CNY',total:0}],error:'hidden',checkedAt:'2026-11-10T02:00:00Z'}}},inspect:async()=>({isFile:()=>true})});
assert.equal(stale.cards[0].balances[2].amount,0);
assert.equal(stale.cards[0].balances[2].low,true);
assert.match(stale.cards[0].detail,/保留上次余额/);
assert.ok(!JSON.stringify(stale).includes('hidden'));
const missing=await readSupportCards({root:'.',inspect:async()=>{throw Error();}});
assert.match(missing.cards[1].fact,/缺少接手资料/);
assert.equal(missing.cards[1].status,'partial');
console.log('PASS support cards: cached balances, missing sources, secret exclusion');
