import assert from 'node:assert/strict';
import { mkdtempSync,rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createOperationsReminders } from '../src/domain/operations-reminders.js';
import { registerObservedAssets,asset } from '../src/domain/asset-catalog.js';
import { workspaceAction,initialWorkspace,contextText } from '../src/domain/workspace.js';
const dir=mkdtempSync(join(tmpdir(),'reminders-'));
let clock=Date.parse('2026-11-10T04:00:00Z');
const service=createOperationsReminders({dir,now:()=>clock++});
try {
  const balance={threshold:5,connections:{sales:{checkedAt:'2026-11-10T04:00:00Z',balances:[{currency:'CNY',total:'4'}]}}};
  service.syncBalance(balance);
  service.syncBalance(balance);
  assert.equal(service.snapshot().issues.length,1);
  assert.equal(service.snapshot().issues[0].occurrences,1);
  balance.connections.sales.balances[0].total='8';
  service.syncBalance(balance);
  assert.equal(service.snapshot().issues.length,0);
  await service.run({area:'knowledge',action:'business-compare'},async()=>({baseline:{generationError:'private text'},augmented:{answer:'ok'}}));
  assert.equal(service.snapshot().issues.length,1,'partial model comparison failure must be recorded');
  assert.ok(!JSON.stringify(service.snapshot()).includes('private text'));
  await service.run({area:'knowledge',action:'business-compare'},async()=>({baseline:{answer:'ok'},augmented:{answer:'ok'}}));
  const meta={area:'model',action:'test',target:'sales'};
  for(let i=0;i<3;i++) await assert.rejects(service.run(meta,async()=>{throw Error('sk-secret-private');}));
  assert.equal(service.snapshot().issues[0].handling,'agent');
  assert.ok(!JSON.stringify(service.snapshot()).includes('sk-secret-private'));
  await service.run(meta,async()=>({ok:true}));
  assert.equal(service.snapshot().issues.length,0);
  const receipt={status:'unknown'};
  assert.equal(await service.run({area:'materials',action:'delete',object:'a'},async()=>receipt),receipt);
  await service.run({area:'materials',action:'delete',object:'b'},async()=>({status:'knownsuccess'}));
  assert.equal(service.snapshot().issues.length,1,'another object cannot resolve this issue');
  registerObservedAssets(service.assets());
  const id=service.snapshot().issues[0].id;
  assert.equal(asset(id).severity,'unknown');
  const state=workspaceAction(initialWorkspace(),{type:'task-add',ids:[id]});
  assert.ok(contextText(state.task,'核对删除').includes('勿重复提交'));
  await service.run({area:'model',action:'test'},async()=>({connected:false}));
  registerObservedAssets(service.assets());
  assert.throws(()=>workspaceAction(state,{type:'task-add',ids:[service.snapshot().issues.find(x=>x.id!==id).id]}));
  assert.equal(createOperationsReminders({dir}).snapshot().issues.length,2);
  console.log('operations reminders: dedup, recovery, redaction, escalation, unknown isolation, persistence PASS');
} finally { rmSync(dir,{recursive:true,force:true}); }
