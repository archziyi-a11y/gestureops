import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { readLocalCards } from '../src/domain/local-card-observations.js';

const root = await mkdtemp(join(tmpdir(), 'local-cards-'));
const manifest = join(root,'corpus_raw/crm/ifangzhou/jyq/manifest.jsonl');
let calls = 0;
const dependencies = {execFile:async (command,args,options) => {
  calls++;
  assert.equal(command,'powershell.exe');
  assert.equal(options.windowsHide,true);
  assert.equal(options.timeout,10000);
  if (args.at(-1).includes('.Triggers')) return {stdout:JSON.stringify({kind:'MSFT_TaskDailyTrigger',enabled:true,days:1,start:'2026-07-17T21:00:00+08:00',repeat:null})};
  assert.match(args.at(-1),/Get-ScheduledTaskInfo/);
  assert.doesNotMatch(args.at(-1),/Start-ScheduledTask|\.Actions/);
  return {stdout:JSON.stringify({state:'Ready',lastRunTime:'2026-11-09T21:00:01+08:00',nextRunTime:'2026-11-10T21:00:00+08:00',lastTaskResult:0,secret:'PRIVATE_SENTINEL'})};
}};
try {
  await mkdir(join(root,'corpus_raw/crm/ifangzhou/jyq'),{recursive:true});
  await mkdir(join(root,'prism/db'),{recursive:true});
  await mkdir(join(root,'prism/media'),{recursive:true});
  await writeFile(join(root,'prism/db/ingestion_contract.sqlite3'),'not a database: stat only');
  await writeFile(manifest,[{asset_type:'image',body:'PRIVATE_SENTINEL',path:'PRIVATE_SENTINEL',sender:'PRIVATE_SENTINEL'},{asset_type:'wechat_note_image'},{asset_type:'wechat_note'},{asset_type:'unexpected'}].map(JSON.stringify).join('\n'));
  let result = await readLocalCards({root,dependencies});
  assert.equal(calls,2);
  assert.ok(Number.isFinite(Date.parse(result.observedAt)));
  assert.deepEqual(result.cards.map(c=>c.id),['jyq','images','prism']);
  assert.equal(result.cards[2].status,'unknown');
  assert.match(result.cards[0].fact,/每天 21:00（\+08:00）/);
  assert.doesNotMatch(result.cards[1].fact,/每 1 天/);
  assert.match(result.cards[1].detail,/历史产出不代表通道健康/);
  assert.match(result.cards[2].fact,/在线服务可用性未确认/);
  assert.match(result.cards[1].fact,/4 条.*2 条/);
  assert.doesNotMatch(JSON.stringify(result),/PRIVATE_SENTINEL/);
  result = await readLocalCards({root,dependencies:{execFile:async()=>{throw Error('PRIVATE_SENTINEL');}}});
  assert.equal(result.cards[0].status,'unknown');
  assert.equal(result.cards[1].status,'observed');
  assert.doesNotMatch(JSON.stringify(result),/PRIVATE_SENTINEL/);
  await writeFile(manifest,'{"asset_type":"image"}\nBROKEN');
  result = await readLocalCards({root,dependencies});
  assert.equal(result.cards[1].status,'unknown');
  assert.doesNotMatch(result.cards[1].fact,/0/);
  assert.equal(result.cards[0].status,'observed');
  assert.equal(result.cards[2].status,'unknown');
  await rm(manifest);
  await rm(join(root,'prism/db/ingestion_contract.sqlite3'));
  result = await readLocalCards({root});
  assert.ok(result.cards.every(c=>c.status==='unknown'));
  assert.match(result.cards[2].detail,/数据库不存在.*媒体目录存在/);
  await writeFile(manifest,'\n');
  await mkdir(join(root,'prism/ops/n8n/workflows'),{recursive:true});
  await writeFile(join(root,'prism/ops/n8n/workflows/prism-feishu-sync-manual.json'),JSON.stringify([{nodes:[{type:'n8n-nodes-base.manualTrigger'}]}]));
  result = await readLocalCards({root,dependencies:{execFile:async()=>({stdout:'{"state":"PRIVATE_SENTINEL"}'})}});
  assert.equal(result.cards[0].status,'unknown');
  assert.match(result.cards[2].detail,/手动触发，无定时刷新配置/);
  assert.match(result.cards[0].fact,/采集频率未知/);
  assert.match(result.cards[1].fact,/0 条/);
  assert.doesNotMatch(JSON.stringify(result),/PRIVATE_SENTINEL/);
  const live = {startedAt:'2026-11-10T06:00:00Z',finishedAt:'2026-11-10T06:00:03Z',channel:{state:'available',secret:'PRIVATE_SENTINEL'},media:{checked:2,readable:1,failed:1},prism:{state:'not_started',processes:0,services:0,tasks:0,listeners:0,readApiConfigured:false,configuredPorts:[{port:8769,listening:false}]}};
  result = await readLocalCards({root,dependencies:{...dependencies,probe:async()=>live}});
  assert.match(result.cards[0].fact,/查询通道可用/);
  assert.match(result.cards[1].fact,/可读 1\/2/);
  assert.match(result.cards[1].issue,/1 条/);
  assert.match(result.cards[2].fact,/服务未启动/);
  assert.equal(result.cards[2].status,'observed');
  assert.doesNotMatch(JSON.stringify(result),/PRIVATE_SENTINEL/);
  live.channel.state='auth_failed';
  live.prism.configuredPorts[0].listening=true;
  result = await readLocalCards({root,dependencies:{...dependencies,probe:async()=>live}});
  assert.match(result.cards[0].fact,/认证失败/);
  assert.equal(result.cards[2].status,'unknown');
  delete live.finishedAt;
  result = await readLocalCards({root,dependencies:{...dependencies,probe:async()=>live}});
  assert.match(result.cards[0].fact,/未完成验证/);
  await assert.rejects(readLocalCards(),/root/);
  console.log('local-card-observations: passed (isolated fixtures, no live reads)');
} finally {
  await rm(root,{recursive:true,force:true});
}
