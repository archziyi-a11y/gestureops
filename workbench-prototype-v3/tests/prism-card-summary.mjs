import assert from 'node:assert/strict';
import {prismCardSummary} from '../src/domain/prism-card-summary.js';
const ok=async()=>({ok:true,json:async()=>({sourceNotes:[{}],mediaManifest:[],localWarnings:[]})});
const complete={kind:'notes',status:'complete',createdAt:'2026-11-11T10:00:00Z'};
let input={collection:{jobs:[complete,{kind:'images',status:'complete'}],archives:[]},localCards:[],fetchPreview:ok};
let card=await prismCardSummary(input);
assert.equal(card.issue,undefined);
assert.match(card.fact,/笔记最近下载完成/);
assert.match(card.fact,/本地预览可读 1 篇/);
input.collection.jobs[0]={...complete,status:'partial',message:'飞书本月 API 额度已用尽'};
card=await prismCardSummary(input);
assert.equal(card.severity,'normal');
assert.match(card.fact,/额度已用尽/);
card=await prismCardSummary({...input,fetchPreview:async()=>{throw Error('down');}});
assert.doesNotMatch(card.fact,/仍可浏览/);
assert.match(card.fact,/无法连接/);
input.collection.jobs[0]=complete;
input.collection.archives=[{createdAt:'2026-11-10T10:00:00Z',errors:[{error:'额度已用尽'}],status:'complete_with_errors'}];
card=await prismCardSummary(input);
assert.equal(card.issue,undefined,'old quota failure cleared by newer successful download');
card=await prismCardSummary({...input,localCards:[{id:'jyq',issue:'通道认证失败',fact:'每天 21:00 · 通道认证失败'}]});
assert.match(card.issue,/通道认证失败/);
assert.match(card.detail,/每天 21:00/);
console.log('PASS Prism summary: success, quota, unavailable preview, recovery, collection channel');
