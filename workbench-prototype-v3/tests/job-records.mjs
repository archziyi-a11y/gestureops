import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,appendFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createJobRecords} from '../src/domain/job-records.js';
const dir=mkdtempSync(join(tmpdir(),'workbench-jobs-'));
let jobs=createJobRecords({dir});
await jobs.run({area:'materials',action:'delete',object:'private-secret'},async()=>({status:'knownsuccess',secret:'never-save'}));
await jobs.run({area:'devices',action:'submit'},async()=>({state:'accepted_not_verified'}));
await jobs.run({area:'materials',action:'upload'},async()=>({status:'unknown'}));
await jobs.run({area:'knowledge',action:'query'},async()=>({generationError:'HTTP 429'}));
await assert.rejects(jobs.run({area:'model',action:'save'},async()=>{throw Error('secret');}));
await jobs.run({area:'materials',action:'list'},async()=>({materials:[]}));
assert.equal(jobs.snapshot().records.length,5);
assert.deepEqual(new Set(jobs.snapshot().records.map(r=>r.state)),new Set(['knownsuccess','accepted_not_verified','unknown','knownfailure']));
assert.ok(!readFileSync(join(dir,'job-records.jsonl'),'utf8').includes('secret'));
appendFileSync(join(dir,'job-records.jsonl'),JSON.stringify({id:'interrupted',area:'devices',action:'submit',state:'running',at:new Date().toISOString()})+'\n');
jobs=createJobRecords({dir});
assert.equal(jobs.snapshot().records.find(r=>r.id==='interrupted').state,'unknown');
assert.equal(jobs.snapshot().records.length,6);
assert.equal(createJobRecords({dir}).snapshot().records.length,6);
console.log('PASS job records: success, failure, unknown, accepted, read exclusion, redaction, restart');
